import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  validateAlgorithmProfile,
  validateBank,
  validateConfiguredPresentation,
  validateRegistry
} from "../../scripts/validate-question-banks.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(here, "..");
const workspaceRoot = path.resolve(projectRoot, "..");
const canonicalDataRoot = path.join(workspaceRoot, "data");

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

function addArtifact(artifacts, target, value) {
  artifacts.push({ target, value });
}

export function createPublicBank(bank) {
  return {
    version: bank.version,
    bank_version: bank.bank_version,
    status: bank.status,
    dimension_config: bank.dimension_config,
    questions: bank.questions.map(({ id, text, type, result_effect, emoji_type, options }) => ({
      id,
      text,
      type,
      result_effect,
      emoji_type,
      options: options.map(({ id: optionId, index, text: optionText }) => ({ id: optionId, index, text: optionText }))
    }))
  };
}

export function createNativeRuntimeModule(registry, banks, presentation) {
  return `// Generated by npm run build:banks. Do not edit.\nmodule.exports = ${JSON.stringify({ registry, banks, presentation }, null, 2)};\n`;
}

export function buildQuestionBanks({
  write = true,
  registry: registryInput,
  banks: banksInput,
  profiles: profilesInput,
  presentation: presentationInput
} = {}) {
  const registry = registryInput || readJson(path.join(canonicalDataRoot, "quiz-versions.v1.json"));
  const presentation = presentationInput || readJson(path.join(canonicalDataRoot, "persona-presentation.v1.json"));
  const profileEntries = profilesInput
    ? Object.values(profilesInput).sort((left, right) => left.id.localeCompare(right.id)).map((profile) => [`${profile.id}.json`, profile])
    : fs.readdirSync(path.join(canonicalDataRoot, "algorithms"))
      .filter((file) => file.endsWith(".json"))
      .sort()
      .map((file) => [file, readJson(path.join(canonicalDataRoot, "algorithms", file))]);
  for (const [, profile] of profileEntries) {
    validateAlgorithmProfile(profile);
  }
  const profiles = Object.fromEntries(profileEntries.map(([, profile]) => [profile.id, profile]));
  const enabledVersions = registry.versions.filter((version) => version.enabled);
  const banks = banksInput || Object.fromEntries(enabledVersions.map((version) => {
    const bank = readJson(path.join(canonicalDataRoot, "banks", `${version.id}.v${version.bank_version}.json`));
    return [version.id, bank];
  }));

  for (const version of enabledVersions) validateBank(banks[version.id], version.tag_prefix);

  validateRegistry(registry, banks, profiles);
  validateConfiguredPresentation(registry, banks, presentation);

  const artifacts = [];
  const publicBanks = {};
  const registryTargets = [
    path.join(projectRoot, "data", "runtime-registry.json"),
    path.join(projectRoot, "cloudfunctions", "get-bank", "data", "runtime-registry.json"),
    path.join(projectRoot, "cloudfunctions", "submit-quiz", "data", "runtime-registry.json"),
    path.join(workspaceRoot, "frontend-demo", "data", "runtime-registry.json")
  ];
  for (const target of registryTargets) addArtifact(artifacts, target, registry);

  for (const version of enabledVersions) {
    const bank = banks[version.id];
    const publicBank = createPublicBank(bank);
    publicBanks[version.id] = publicBank;
    const privateFile = `${version.id}.v${version.bank_version}.json`;
    const publicFile = `${version.id}.v${version.bank_version}.public.json`;

    addArtifact(artifacts, path.join(projectRoot, "data", "banks", privateFile), bank);
    addArtifact(artifacts, path.join(projectRoot, "cloudfunctions", "submit-quiz", "data", "banks", privateFile), bank);
    addArtifact(artifacts, path.join(projectRoot, "cloudfunctions", "get-bank", "data", publicFile), publicBank);
    addArtifact(artifacts, path.join(workspaceRoot, "frontend-demo", "data", publicFile), publicBank);
  }

  addArtifact(
    artifacts,
    path.join(workspaceRoot, "miniprogram", "data", "runtime.js"),
    createNativeRuntimeModule(registry, publicBanks, presentation)
  );

  for (const [file, profile] of profileEntries) {
    addArtifact(artifacts, path.join(projectRoot, "data", "algorithms", file), profile);
    addArtifact(artifacts, path.join(projectRoot, "cloudfunctions", "submit-quiz", "data", "algorithms", file), profile);
  }

  if (write) for (const { target, value } of artifacts) {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, typeof value === "string" ? value : `${JSON.stringify(value, null, 2)}\n`, "utf8");
  }

  return artifacts;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const artifacts = buildQuestionBanks();
  const bankCount = artifacts.filter(({ target }) => target.includes(`${path.sep}banks${path.sep}`) && target.includes(`${path.sep}data${path.sep}`)).length / 2;
  console.log(`Built ${bankCount} banks`);
}
