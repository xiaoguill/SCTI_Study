const tagMap = new Map(tags.map((tag) => [tag.id, tag]));
const deriveOptionDimensions = (scoreMap, effect) => {
  if (effect === "egg_only") return [3, 3, 3, 3];
  const sums = [0, 0, 0, 0];
  let weight = 0;
  for (const [tagId, score] of Object.entries(scoreMap)) {
    const tag = tagMap.get(tagId);
    if (!tag || !score) continue;
    tag.dimensions.forEach((value, index) => { sums[index] += value * score; });
    weight += score;
  }
  return weight ? sums.map((value) => Number((value / weight).toFixed(2))) : [3, 3, 3, 3];
};

