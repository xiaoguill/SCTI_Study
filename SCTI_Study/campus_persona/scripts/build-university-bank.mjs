function validate() {
  if (tags.length !== 16) throw new Error("大学版必须包含 16 个标签");
  if (privateQuestions.length !== 20) throw new Error("大学版必须包含 20 道题");
  for (const question of privateQuestions) {
    const expected = question.id === 20 ? 16 : 4;
    if (question.options.length !== expected) throw new Error(`Q${question.id} 选项数量错误`);
    if (!["scored", "egg_only"].includes(question.result_effect)) throw new Error(`Q${question.id} 缺少 result_effect`);
    for (const option of question.options) {
      for (const score of Object.values(option.scores)) {
        if (![0, 1, 2].includes(score)) throw new Error(`Q${question.id} 存在非法权重`);
      }
    }
  }
  for (const tag of tags) {
    if (tag.core_questions.length < 2 || tag.core_questions.length > 3) throw new Error(`${tag.id} 核心题数量错误`);
  }
}

